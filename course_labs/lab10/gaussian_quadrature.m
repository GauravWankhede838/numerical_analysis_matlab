function [integral] = gaussian_quadrature(f, a, b, n)
  
    switch n
        case 2
            t = [-1/sqrt(3), 1/sqrt(3)];
            w = [1, 1];
        case 3
            t = [-sqrt(3/5), 0, sqrt(3/5)];
            w = [5/9, 8/9, 5/9];
        case 4
            t = [-0.861136311594053, -0.339981043584856, 0.339981043584856, 0.861136311594053];
            w = [ 0.347854845137454,  0.652145154862546, 0.652145154862546, 0.347854845137454];
        case 5
            t = [-0.906179845938664, -0.538469310105683, 0, 0.538469310105683, 0.906179845938664];
            w = [ 0.236926885056189,  0.478628670499366, 128/225, 0.478628670499366, 0.236926885056189];
        otherwise
            error('n must be 2, 3, 4 or 5');
    end

    x = (b-a)/2 * t + (b+a)/2;

    integral = (b-a)/2 * sum(w .* f(x));

end